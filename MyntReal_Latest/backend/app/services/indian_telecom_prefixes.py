def resolve_indian_prefix(mobile: str) -> Tuple[str, str, str, str]:
    """
    Resolves 10-digit Indian mobile number to (ui_operator, op_code, circle_name, circle_code).
    1. Check 4-digit MSC prefix in 1,893+ master entries.
    2. Check 3-digit prefix.
    3. Check 2-digit series.
    4. Default to ('Jio', 'RC', 'Andhra Pradesh', '49').
    """
    clean = re.sub(r"\D", "", mobile or "")
    if len(clean) == 12 and clean.startswith("91"):
        clean = clean[2:]
    elif len(clean) > 10:
        clean = clean[-10:]

    if len(clean) < 4:
        return ("Jio", "RC", "Andhra Pradesh", "49")

    p4 = clean[:4]
    if p4 in INDIAN_PREFIX_4_DIGIT:
        return INDIAN_PREFIX_4_DIGIT[p4]

    p3 = clean[:3]
    if p3 in INDIAN_SERIES_3_DIGIT:
        return INDIAN_SERIES_3_DIGIT[p3]

    p2 = clean[:2]
    if p2 in INDIAN_SERIES_2_DIGIT:
        return INDIAN_SERIES_2_DIGIT[p2]

    # Default to India's largest telecom provider
    return ("Jio", "RC", "Andhra Pradesh", "49")
